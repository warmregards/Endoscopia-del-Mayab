#!/usr/bin/env node
// Generates lib/sitemap-lastmod.ts — per-route last-modified dates sourced from
// each page's last git commit date (committer date, W3C YYYY-MM-DD).
//
// Why: app/sitemap.ts used to stamp every URL with new Date() at build time, so
// all URLs shared one build timestamp that changed on every deploy — the
// canonical "unreliable lastmod" pattern Google discounts. A committed map from
// git commit dates is stable across deploys and only changes when a route's
// content actually changes.
//
// Run from the repo root after content changes:
//   node scripts/gen-sitemap-lastmod.mjs
import { execSync } from "node:child_process"
import { readdirSync, existsSync, writeFileSync } from "node:fs"
import { join } from "node:path"

const SITE_DIR = "app/(site)"

/** Last git commit date (YYYY-MM-DD) that touched a file, or "" if none. */
function gitDate(file) {
  try {
    return execSync(`git log -1 --format=%cs -- "${file}"`, {
      encoding: "utf8",
    }).trim()
  } catch {
    return ""
  }
}

const entries = {}

// Homepage lives at the (site) group root.
const rootPage = join(SITE_DIR, "page.tsx")
if (existsSync(rootPage)) entries["/"] = gitDate(rootPage)

for (const dirent of readdirSync(SITE_DIR, { withFileTypes: true })) {
  if (!dirent.isDirectory()) continue
  if (dirent.name === "servicios") continue // 301 → /, not in the sitemap
  const page = join(SITE_DIR, dirent.name, "page.tsx")
  if (!existsSync(page)) continue
  const date = gitDate(page)
  if (date) entries[`/${dirent.name}`] = date
}

const keys = Object.keys(entries).sort()
const body = keys
  .map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(entries[k])},`)
  .join("\n")

const out = `// AUTO-GENERATED by scripts/gen-sitemap-lastmod.mjs — do not edit by hand.
// Per-route last-modified dates (W3C YYYY-MM-DD) from each page's last git
// commit, so the sitemap lastmod is stable across deploys and only moves when a
// route's content actually changes (vs. a build-time new Date() on every URL).
// Regenerate after content changes:  node scripts/gen-sitemap-lastmod.mjs
//
// Caveat: reflects each page file's OWN commits. If you change a route's
// rendered content only through a shared lib module (faq.ts, pricing.ts,
// routes-seo.ts, services.ts) without editing its page.tsx, bump that route
// here by hand (or touch the page file) before regenerating.
export const ROUTE_LASTMOD: Record<string, string> = {
${body}
}
`

writeFileSync("lib/sitemap-lastmod.ts", out)
console.log(`Wrote lib/sitemap-lastmod.ts with ${keys.length} routes`)
